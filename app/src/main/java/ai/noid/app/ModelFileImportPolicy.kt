package ai.noid.app

/**
 * Pure validation for user-selected LiteRT-LM model files.
 * The runtime performs the authoritative model-format validation at load time.
 */
object ModelFileImportPolicy {
    const val MAX_MODEL_BYTES = 8L * 1024L * 1024L * 1024L

    fun isSupportedName(displayName: String?): Boolean {
        val normalized = displayName?.trim()?.lowercase() ?: return false
        if (normalized.isBlank() || normalized.length > 240) return false
        if (normalized.any { it.isISOControl() || it == '/' || it == '\\' }) return false
        return normalized.endsWith(".litertlm") &&
            normalized.removeSuffix(".litertlm").isNotBlank()
    }

    /** Stored names are generated by NOID and must never escape the private models directory. */
    fun isSafeStoredFileName(fileName: String?): Boolean {
        if (fileName.isNullOrBlank() || fileName.length > 80) return false
        if (fileName.any { it.isISOControl() || it == '/' || it == '\\' }) return false
        return fileName.startsWith("model-") && fileName.endsWith(".litertlm") &&
            fileName.removePrefix("model-").removeSuffix(".litertlm").toLongOrNull() != null
    }

    fun isSupportedSize(sizeBytes: Long): Boolean =
        sizeBytes in 1..MAX_MODEL_BYTES

    /** Requires the model plus a reserve, without overflow-prone addition. */
    fun hasSufficientSpace(
        modelSizeBytes: Long?,
        availableBytes: Long,
        reserveBytes: Long
    ): Boolean {
        if (availableBytes < 0L || reserveBytes < 0L || availableBytes < reserveBytes) {
            return false
        }
        if (modelSizeBytes == null) return true
        if (!isSupportedSize(modelSizeBytes)) return false
        return modelSizeBytes <= availableBytes - reserveBytes
    }

    /** Enforces the initial free-space budget even when a document provider lies about file size. */
    fun canCopyWithinBudget(
        copiedBytes: Long,
        nextChunkBytes: Int,
        availableBytes: Long,
        reserveBytes: Long
    ): Boolean {
        if (copiedBytes < 0L || nextChunkBytes < 0 || availableBytes < 0L ||
            reserveBytes < 0L || availableBytes < reserveBytes
        ) return false
        val budget = minOf(MAX_MODEL_BYTES, availableBytes - reserveBytes)
        return copiedBytes <= budget && nextChunkBytes.toLong() <= budget - copiedBytes
    }
}
